/**
 * Intelligent fuzzy and prefix search for colleges.
 * Matches:
 * 1. Exact name or prefix
 * 2. Acronym / short name / alias (e.g., 'BIT' -> 'Bannari Amman Institute of Technology')
 * 3. Individual words in college name
 * 4. Location (e.g., 'Sathy', 'Coimbatore', 'Chennai')
 */
export function searchColleges(query, limit = 8) {
  if (!query || !query.trim()) {
    // Return top popular recommendations when empty or focused
    return COLLEGES_DATA.slice(0, limit);
  }

  const cleanQuery = query.trim().toLowerCase();
  const queryTokens = cleanQuery.split(/\s+/).filter(Boolean);

  const scored = [];

  for (const college of COLLEGES_DATA) {
    const nameLower = college.name.toLowerCase();
    const shortLower = college.shortName.toLowerCase();
    const locLower = college.location.toLowerCase();
    const aliasLower = (college.aliases || []).map(a => a.toLowerCase());

    let score = 0;

    // Direct startsWith name
    if (nameLower.startsWith(cleanQuery)) {
      score += 100;
    } else if (shortLower.startsWith(cleanQuery)) {
      score += 90;
    } else if (aliasLower.some(a => a === cleanQuery)) {
      score += 95;
    } else if (aliasLower.some(a => a.startsWith(cleanQuery))) {
      score += 80;
    } else if (nameLower.includes(cleanQuery)) {
      score += 60;
    } else if (locLower.includes(cleanQuery)) {
      score += 40;
    }

    // Token matching (all tokens must appear somewhere in name, location, or aliases)
    const allText = `${nameLower} ${shortLower} ${locLower} ${aliasLower.join(' ')}`;
    const allTokensMatch = queryTokens.every(tok => allText.includes(tok));
    if (allTokensMatch) {
      score += 30;
      // Bonus if any word in the name starts with the first token
      const words = nameLower.split(/\s+/);
      if (words.some(w => w.startsWith(queryTokens[0]))) {
        score += 20;
      }
    }

    if (score > 0) {
      scored.push({ college, score });
    }
  }

  // Sort descending by match score
  scored.sort((a, b) => b.score - a.score);

  return scored.slice(0, limit).map(item => item.college);
}
